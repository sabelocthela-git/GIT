def add_nums(a,b):
    """Reurns the sum of a and b."""
    return a + b

def divide_nums(a,b):
    """Reurns the division of a and b."""
    return a / b

def subtract_nums(a,b):
    """Reurns the difference of a and b."""
    return a - b

def power_nums(a,b):
    """Reurns the power of a to b."""
    return a ** b

def multiply_nums(a,b):
    """Reurns the product of a and b."""
    return a * b
